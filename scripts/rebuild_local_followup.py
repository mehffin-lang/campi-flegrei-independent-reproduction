"""Rebuild continuation figures/documents; --analysis also reruns frozen inputs.

No waveform downloads. Visual judgments are retained observations, not generated
by rerunning code. Generic method resources can be retrieved by --analysis only.
"""
from pathlib import Path
import argparse,hashlib,json,subprocess,sys
ROOT=Path(__file__).resolve().parents[1];D=ROOT/'data/local_extension'
def main():
    ap=argparse.ArgumentParser();ap.add_argument('--analysis',action='store_true');ap.add_argument('--reuse-plots',action='store_true',help='Verify saved plot input/output hashes and compile documents without redrawing.');args=ap.parse_args()
    assert not (args.analysis and args.reuse_plots),'Analysis changes require regenerating plots.'
    runs=[];logdir=ROOT/'tmp/local_followup_rebuild';logdir.mkdir(exist_ok=True)
    def run(script,*arguments):
        cmd=[sys.executable,'scripts/'+script,*arguments];path=logdir/(script+'.log')
        with path.open('w') as stream:result=subprocess.run(cmd,cwd=ROOT,stdout=stream,stderr=subprocess.STDOUT)
        runs.append(dict(command=cmd,returncode=result.returncode,log=str(path.relative_to(ROOT))))
        (D/'rebuild_result.json').write_text(json.dumps(dict(analysis_requested=args.analysis,runs=runs,passed=False),indent=2)+'\n')
        if result.returncode:raise RuntimeError(str(path))
    checkpoint=json.loads((D/'processing_checkpoint.json').read_text())
    revisions=json.loads((D/'source_revision.json').read_text()) if (D/'source_revision.json').exists() else {}
    for name,h in checkpoint['files'].items():
        if name==revisions.get('current_source'):
            assert hashlib.sha256((ROOT/revisions['executed_source']).read_bytes()).hexdigest()==h
            h=revisions['current_sha256']
        assert hashlib.sha256((ROOT/name).read_bytes()).hexdigest()==h,name
    if args.analysis:
        run('process_local_followup.py','--frozen','--workers','4')
        run('audit_continuation.py','--data-dir','data/local_extension')
        run('acquisition_ledger.py','--data-dir','data/local_extension','--snapshot','data/local_extension/acquisition_snapshot.json')
        run('calibrate_local_followup.py')
        run('prepare_mechanism_software.py')
        run('mechanism_measurements.py')
        run('run_reviewed_skhash.py')
        run('run_gcap_followup.py')
        run('run_gcap_followup.py','--high-band')
        run('validate_mechanism_followup.py')
    if args.reuse_plots:
        for plot in json.loads((ROOT/'data/mechanism_followup/plot_inventory.json').read_text()):
            for name,h in dict(plot['inputs'],**plot['outputs']).items():
                assert hashlib.sha256((ROOT/name).read_bytes()).hexdigest()==h,name
    else:run('plot_local_followup.py')
    run('local_followup_report.py')
    run('build_documents.py','--clean')
    plots=json.loads((ROOT/'data/mechanism_followup/plot_inventory.json').read_text())
    build=json.loads((ROOT/'report/document_build.json').read_text())
    result=dict(analysis_requested=args.analysis,reused_hash_verified_plots=args.reuse_plots,runs=runs,passed=True,scientific_acceptance=False,document_order_verified=build['build_passed'],plots=len(plots),note='Presentation rebuild from executed numerical outputs unless --analysis requested. Inference caches and unchanged own daily associations may be reused after checks. Human review is not generated by this command.')
    (D/'rebuild_result.json').write_text(json.dumps(result,indent=2)+'\n');print(json.dumps(result,indent=2))
if __name__=='__main__':main()
